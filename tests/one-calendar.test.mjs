import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import { toInstant, wallTime, eventValues, monthGrid, addDays, shiftMonth } from '../src/pages/one/calendar-time.mjs';
assert.equal(toInstant('2026-11-04T09:00'), '2026-11-04T08:00:00.000Z');
assert.equal(toInstant('2026-07-04T09:00'), '2026-07-04T07:00:00.000Z');
assert.equal(wallTime('2026-11-04T08:00:00Z'), '2026-11-04T09:00');
assert.throws(() => toInstant('2026-03-29T02:30'), /zomertijd/);
assert.throws(() => toInstant('2026-10-25T02:30'), /wintertijd/);
assert.throws(() => toInstant('2026-02-31T09:00'), /Ongeldige datum/);
assert.throws(() => toInstant('2026-11-04T24:00'), /geldige datum/);
assert.equal(addDays('2026-12-31', 1), '2027-01-01');
assert.equal(shiftMonth('2026-12', 1), '2027-01');
assert.equal(monthGrid('2026-11').length, 42);
assert.equal(monthGrid('2026-11')[0], '2026-10-26');
const draft = { title: 'Test', kind: 'private', startDate: '2026-03-29', endDate: '2026-03-29', startTime: '09:00', endTime: '10:00', allDay: true, location: '', notes: '', reminder: '0' };
const day = eventValues(draft);
assert.equal((new Date(day.ends_at) - new Date(day.starts_at)) / 3600000, 23, 'DST all-day event is 23 real hours, not 24');
assert.equal(eventValues({ ...draft, startDate: '2026-10-25', endDate: '2026-10-25' }).ends_at, '2026-10-25T23:00:00.000Z');
assert.throws(() => eventValues({ ...draft, allDay: false, endTime: '08:00' }), /eindtijd/);
assert.throws(() => eventValues({ ...draft, title: ' ' }), /titel/);
assert.throws(() => eventValues({ ...draft, reminder: '15' }), /herinnering/);
assert.equal(eventValues({ ...draft, reminder: '' }).reminder_minutes, null);
